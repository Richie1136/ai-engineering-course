# =====================================================
# Text Classification
# =====================================================

# Text classification is the process of assigning a label
# or category to a piece of text.

# Examples:
# - Spam vs. Not Spam
# - Positive vs. Negative sentiment
# - Fake vs. Real news
# - Sports vs. Politics vs. Technology

# Typical NLP classification pipeline:
#
# 1. Load the dataset
# 2. Clean and preprocess the text
# 3. Convert text into numerical features
#    - Bag of Words
#    - TF-IDF
# 4. Split into training and testing data
# 5. Train a machine learning model
#    - Logistic Regression
#    - Naive Bayes
#    - Support Vector Machine (SVM)
# 6. Make predictions
# 7. Evaluate the model
#    - Accuracy
#    - Precision
#    - Recall
#    - F1 Score