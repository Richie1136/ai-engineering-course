# NOT - AND - OR

# Logical operators = Boolean operators

# and checks whether the two statements around it are True

print(True and True)
print(True and False)
print(False and False)

# or checks whether at least one of the two statements is True

print(False or False)
print(True or True)
print(True or False)

# not leads to the opposite of the given statement

print(not True)
print(not False)
print(3 > 5 and 10 <= 20) 

# Not - And - Or

print(True and not True)
print(False or not True and True)
print(True and not True or True)

# Identity Operators

# is, is not

print(5 is 6)
print(5 == 6)
print(5 is not 6)
print(5 != 6)