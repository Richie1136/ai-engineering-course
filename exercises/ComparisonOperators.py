# WHY: Comparisons answer yes/no questions and therefore produce Boolean values
# (`True` or `False`). Those results later control conditionals and loops.
# Mental model: compare two values -> receive a Boolean decision.

print(10 != 10)
print(10 != 15) # != means not equal
print(100 > 50)
print(100 < 50)
print(15 >= 10 + 10)
print(15 <= 10 + 5)